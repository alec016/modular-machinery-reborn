package es.degrassi.mmr.mixin;

import es.degrassi.mmr.ModularMachineryReborn;
import es.degrassi.mmr.common.data.MMRConfig;
import es.degrassi.mmr.common.item.ControllerItem;
import es.degrassi.mmr.common.registration.BlockRegistration;
import es.degrassi.mmr.common.registration.DataComponentRegistration;
import es.degrassi.mmr.data.advancements.AdvancementTexts;
import net.minecraft.advancements.Advancement;
import net.minecraft.advancements.criterion.DataComponentMatchers;
import net.minecraft.advancements.criterion.InventoryChangeTrigger;
import net.minecraft.advancements.criterion.ItemPredicate;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.component.DataComponentExactPredicate;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.Identifier;
import net.minecraft.server.ServerAdvancementManager;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.SimpleJsonResourceReloadListener;
import net.minecraft.util.profiling.ProfilerFiller;
import net.minecraft.world.item.ItemStackTemplate;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

import java.util.Map;

/**
 * This can not be achieved with this mixin, I don't remove it to keep track of how I want to do it in other approach.
 * It isn't added to mixin config, so it will never be triggered on world reload (it is the only point it will be
 * triggered, and it's not saved at any point as is not really registered)
 */
@Mixin(ServerAdvancementManager.class)
@SuppressWarnings("removal")
@Deprecated(forRemoval = true)
public abstract class ServerAdvancementManagerMixin extends SimpleJsonResourceReloadListener<Advancement> {
  public ServerAdvancementManagerMixin(HolderLookup.Provider registries) {
    super(registries, Advancement.CODEC, Registries.ADVANCEMENT);
  }

  @Inject(at = @At(value = "HEAD"), method = "apply(Ljava/util/Map;" +
      "Lnet/minecraft/server/packs/resources/ResourceManager;" +
      "Lnet/minecraft/util/profiling/ProfilerFiller;)V")
  private void injectCustomAdvancements(Map<Identifier, Advancement> preparations, ResourceManager manager, ProfilerFiller profiler, CallbackInfo ci) {
    var config = MMRConfig.get();
    if (config.enableAutoGeneratedAchievements.get()) {
      var whitelist = config.machineIdWhitelist.get();
      var machineIds = config.machineIds.get();
      var type = config.defaultAdvancementType.get();
      ModularMachineryReborn.MACHINES.entrySet().stream()
          .filter(id -> {
            if (whitelist) return machineIds.contains(id.getKey());
            else return !machineIds.contains(id.getKey());
          })
          .forEach(id -> {
            var name = id.getValue().getLocalizedName();
            var advancement = new Advancement.Builder()
                .parent(ModularMachineryReborn.rl("main/controller"))
                .display(
                    ItemStackTemplate.fromNonEmptyStack(ControllerItem.makeMachineItem(id.getKey())),
                    AdvancementTexts.Generated.text(name),
                    AdvancementTexts.GeneratedDesc.text(name),
                    null,
                    type,
                    true,
                    true,
                    false
                )
                .addCriterion(
                    name,
                    InventoryChangeTrigger
                        .TriggerInstance
                        .hasItems(
                            ItemPredicate
                                .Builder
                                .item()
                                .of(
                                    getRegistryLookup().lookupOrThrow(Registries.ITEM),
                                    BlockRegistration.CONTROLLER
                                ).withComponents(
                                    DataComponentMatchers
                                        .Builder
                                        .components()
                                        .exact(
                                            DataComponentExactPredicate
                                                .builder()
                                                .expect(DataComponentRegistration.MACHINE_DATA.get(), id.getKey())
                                                .build()
                                        )
                                        .build()
                                )
                        )
                )
                .build(ModularMachineryReborn.rl("generated/controller/%s".formatted(id.getKey().getPath())));
            preparations.put(advancement.id(), advancement.value());
          });
    }
  }
}
